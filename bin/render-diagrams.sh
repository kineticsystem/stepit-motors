#!/bin/bash -e

# Renders every diagram of docs/diagrams/*.mmd into an SVG next to it, which the
# documents show as an image: GitHub draws an image at the width we give it, and
# a Mermaid block as wide as the page. Each SVG starts with the SHA-256 of its
# source, so bin/check-diagrams.sh fails when one is out of date.
#
# Run it after changing a .mmd file, outside the container: it needs Node.js
# and Google Chrome or Chromium, and runs mermaid-cli 11, the Mermaid of GitHub.

cd "$(dirname "$(readlink -f "$0")")/.."

chrome=$(command -v google-chrome || command -v google-chrome-stable || command -v chromium || command -v chromium-browser || true)
[ -n "$chrome" ] || { echo "Google Chrome or Chromium is needed to render the diagrams." >&2; exit 1; }
puppeteer=$(mktemp --suffix .json)
trap 'rm -f "$puppeteer"' EXIT
echo "{\"executablePath\":\"$chrome\",\"args\":[\"--no-sandbox\"]}" > "$puppeteer"

for source in docs/diagrams/*.mmd; do
    [ -f "$source" ] || continue
    svg=${source%.mmd}.svg
    PUPPETEER_SKIP_DOWNLOAD=1 npx -y @mermaid-js/mermaid-cli@11 -q -p "$puppeteer" -b transparent -i "$source" -o "$svg"
    hash=$(sha256sum "$source" | cut -d ' ' -f 1)
    sed -i "1i <!-- Generated by bin/render-diagrams.sh from $(basename "$source"), sha256 $hash. Do not edit. -->" "$svg"
    # End with a newline, as the end-of-file-fixer hook of pre-commit wants.
    [ -z "$(tail -c 1 "$svg")" ] || echo >> "$svg"
    width=$(grep -o 'max-width: [0-9.]*' "$svg" | head -n 1 | cut -d ' ' -f 2)
    echo "$svg: width $width px"
done
